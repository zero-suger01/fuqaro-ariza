def t(language: str, key: str, **kwargs) -> str:
    texts = _TEXTS.get(language, _TEXTS["uz"])
    template = texts.get(key, _TEXTS["uz"].get(key, key))
    return template.format(**kwargs) if kwargs else template


def find_key_by_text(text: str) -> str | None:
    """Reply-keyboard tugmalari matnini tilidan qat'i nazar aniqlaydi —
    foydalanuvchi tilni almashtirsa ham eski klaviatura matni tanilishi
    uchun barcha tillar bo'yicha qidiradi."""
    for lang_texts in _TEXTS.values():
        for key, value in lang_texts.items():
            if value == text:
                return key
    return None


